import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { renderWebview } from '../host/webview.cjs';
import { createSettingsConfiguration } from '../harness/config/settings-config.cjs';

test('operation errors preserve drafts, show safe details, dismiss and recover from timeouts', async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage();
    await page.addInitScript(() => { window.sent = []; window.acquireVsCodeApi = () => ({ getState() {}, setState() {}, postMessage: m => { if (window.failSend) throw new Error('bridge unavailable'); window.sent.push(m); } }); });
    await page.route('**/*', route => route.fulfill({ contentType: 'text/html', body: renderWebview() }));
    await page.goto('http://errors.test/');
    await page.clock.install();
    const send = data => page.evaluate(data => window.dispatchEvent(new MessageEvent('message', { data })), data);
    const state = id => ({ type: 'state', mode: 'assist', conversation: { id }, messages: [], context: {}, provider: { configured: true }, execution: { status: 'idle', workers: [], activities: [] }, busy: false });
    await send(state('a'));
    const composer = page.locator('#prompt-input');
    await composer.fill('保留这份草稿');
    await composer.press('Enter');
    const request = await page.evaluate(() => window.sent.findLast(m => m.action === 'prompt'));
    assert.ok(request);
    await send({ type: 'uiResult', requestId: request.requestId, ok: false, error: 'ECONNREFUSED token=private' });
    assert.match(await page.locator('#ui-error-message').innerText(), /无法连接/);
    assert.equal(await page.locator('#ui-error-title').innerText(), '发送消息未完成');
    assert.doesNotMatch(await page.locator('#ui-error-detail').textContent(), /private/);
    assert.equal(await composer.inputValue(), '保留这份草稿');
    await send(state('b')); assert.equal(await page.locator('#ui-error').isVisible(), false);
    await send(state('a')); assert.equal(await page.locator('#ui-error').isVisible(), true);
    await page.locator('#ui-error-dismiss').click(); assert.equal(await page.locator('#ui-error').isVisible(), false);
    await composer.press('Enter');
    const timedOut = await page.evaluate(() => window.sent.findLast(m => m.action === 'prompt'));
    await page.clock.fastForward(120001);
    assert.match(await page.locator('#ui-error-message').innerText(), /超时/);
    assert.equal(await composer.inputValue(), '保留这份草稿');
    await send({ type: 'uiResult', requestId: timedOut.requestId, ok: true });
    assert.equal(await composer.inputValue(), '保留这份草稿');
    await composer.press('Enter');
    const cancelled = await page.evaluate(() => window.sent.findLast(m => m.action === 'prompt'));
    await send({ type: 'uiResult', requestId: cancelled.requestId, ok: false, failure: { name: 'AbortError' } });
    assert.equal(await page.locator('#ui-error-title').innerText(), '发送消息已取消');
    assert.equal(await page.locator('#ui-error').getAttribute('role'), 'status');
    const service = createSettingsConfiguration({ workspace: { getConfiguration: () => ({ inspect: () => ({}) }) } }, { secrets: { get: async () => undefined } });
    await send({ type: 'openSettings', data: await service.snapshot() });
    await page.locator('#settings-reload').click();
    const invalid = await page.evaluate(() => window.sent.findLast(m => m.action === 'settingsRead'));
    await send({ type: 'settingsResult', requestId: invalid.requestId, ok: false });
    assert.match(await page.locator('#settings-status').innerText(), /未收到有效/);
    assert.equal(await page.locator('#settings-reload').isDisabled(), false);
    await page.locator('#settings-reload').click();
    await page.clock.fastForward(30001);
    assert.equal(await page.locator('#settings-reload').isDisabled(), false);
    assert.match(await page.locator('#settings-status').innerText(), /超时/);
    await page.locator('#settings-close').click();
    await page.evaluate(() => { window.failSend = true; });
    await composer.press('Enter');
    assert.match(await page.locator('#ui-error-message').innerText(), /未能发送/);
    await page.clock.fastForward(120001);
    assert.match(await page.locator('#ui-error-message').innerText(), /未能发送/);
    assert.equal(await composer.inputValue(), '保留这份草稿');
  } finally { await browser.close(); }
});
